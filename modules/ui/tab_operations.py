from tkinter import ttk


def build_operations_tab(app):
    tab = ttk.Frame(app.notebook, padding=12)
    app.notebook.add(tab, text="Operations")
    ttk.Label(tab, text="Operations to perform", font=("TkDefaultFont", 11, "bold")).pack(anchor="w")
    ttk.Checkbutton(tab, text="Convert audio to AAC (EAC3 → AAC)", variable=app.vars["audio_convert"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Filter audio tracks (configured in Audio tab)", variable=app.vars["audio_filter_enabled"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Convert video to HEVC", variable=app.vars["video_convert"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Remove HDR / Convert to SDR (Tonemapping)", variable=app.vars["remove_hdr"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Use CROP", variable=app.vars["crop_enabled"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Use CUT", variable=app.vars["cut_enabled"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Insert external SRT", variable=app.vars["subtitle_insert"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Export audio to .m4a", variable=app.vars["export_audio"]).pack(anchor="w", pady=3)
    ttk.Checkbutton(tab, text="Extract subtitles from MKV", variable=app.vars["extract_subs"]).pack(anchor="w", pady=3)
    row = ttk.Frame(tab)
    row.pack(anchor="w", pady=7)
    ttk.Label(row, text="Manual audio tracks to keep (e.g. 1,2 - empty = all/Audio tab):").pack(side="left")
    ttk.Entry(row, textvariable=app.vars["audio_tracks_to_keep"], width=18).pack(side="left", padx=6)
    row = ttk.Frame(tab)
    row.pack(anchor="w", pady=5)
    ttk.Label(row, text="Container:").pack(side="left")
    ttk.OptionMenu(row, app.vars["container_format"], ".mkv", ".mkv", ".mp4", ".mov").pack(side="left", padx=6)
    ttk.Separator(tab).pack(fill="x", pady=15)
    ttk.Label(tab, text="HEVC Quality", font=("TkDefaultFont", 11, "bold")).pack(anchor="w")
    q = ttk.Frame(tab)
    q.pack(fill="x", pady=8)
    ttk.Label(q, text="CQ / CRF (lower = higher quality):").pack(side="left")
    ttk.Scale(q, from_=20, to=32, variable=app.vars["quality"], orient="horizontal", length=300).pack(side="left", padx=8)
    ttk.Label(q, textvariable=app.vars["quality"], width=4).pack(side="left")
    er = ttk.Frame(tab)
    er.pack(anchor="w", pady=4)
    ttk.Label(er, text="Encoder:").pack(side="left")
    ttk.OptionMenu(er, app.vars["encoder"], "auto", "auto", "nvenc", "cpu (x265)").pack(side="left", padx=6)
    ttk.Label(er, text="NVENC preset:").pack(side="left", padx=(20, 0))
    ttk.OptionMenu(er, app.vars["nvenc_preset"], "p5", "p1", "p2", "p3", "p4", "p5", "p6", "p7").pack(side="left", padx=6)
    ttk.Label(tab, text="Recommendation for smaller files: CPU/x265 + slow preset. NVENC is faster, but usually less efficient at the same visual quality.", wraplength=850, foreground="#555").pack(anchor="w", pady=15)
